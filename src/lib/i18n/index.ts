export type DictKey = keyof (typeof dict)["en"];

export function t(locale: Locale, key: DictKey): string {
  const value = dict[locale][key];
  const fallback = dict.en[key];
  return (value ?? fallback) as string;
}

export function getLocale(cookieValue: string | undefined, userLocale?: string | null): Locale {
  if (isLocale(cookieValue ?? "")) return cookieValue as Locale;
  if (isLocale(userLocale ?? "")) return userLocale as Locale;
  return "en";
}
